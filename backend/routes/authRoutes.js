const router = require('express').Router();
const { protect, allowRoles, requirePermission, requireIntegrationOtp } = require('../middleware/auth');
const manageSettings = requirePermission('settings', 'manage');
const ctrl = require('../controllers/authController');
const { limits } = require('../middleware/rateLimit');

router.post('/signup', limits.signup, ctrl.signup);
router.post('/login', limits.loginIp, limits.login, ctrl.login);
router.post('/request-integration-otp', protect, limits.integrationCode, allowRoles('admin'), manageSettings, ctrl.requestIntegrationOtp);
router.post('/verify-integration-otp', protect, limits.integrationCode, allowRoles('admin'), manageSettings, ctrl.verifyIntegrationOtp);
router.post('/verify-integration-pin', protect, limits.integrationCode, allowRoles('admin'), manageSettings, ctrl.verifyIntegrationPin);
router.get('/settings', ctrl.getAuthSettings);
router.get('/settings/manage', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.getAuthSettings);
router.patch('/settings', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.updateAuthSettings);
router.get('/google-clients', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.getGoogleOAuthConfig);
router.put('/google-clients', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.saveGoogleOAuthClient);
router.get('/recaptcha-clients', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.getRecaptchaConfig);
router.put('/recaptcha-clients', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.saveRecaptchaClient);
router.post('/integrations/restore-defaults', protect, allowRoles('admin'), manageSettings, requireIntegrationOtp('access'), ctrl.restoreIntegrationDefaults);
router.get('/recaptcha-config', ctrl.recaptchaConfig);
router.post('/google/start', limits.googleSignIn, ctrl.googleStartWithCaptcha);
router.get('/google', ctrl.googleStart);
router.get('/google/callback', ctrl.googleCallback);
router.post('/google/exchange', limits.googleSignIn, ctrl.googleExchange);
router.post('/logout', protect, ctrl.logout);
router.get('/me', protect, ctrl.me);
router.post('/forgot-password', limits.passwordReset, ctrl.forgotPassword);
router.post('/verify-reset-otp', limits.passwordReset, ctrl.verifyResetOtp);
router.post('/resend-reset-otp', limits.passwordReset, ctrl.resendResetOtp);
router.post('/reset-password', limits.passwordReset, ctrl.resetPassword);

module.exports = router;
